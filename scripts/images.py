#!/usr/bin/env python3
"""Scan public/images and emit a typed TS manifest with dimensions + blur placeholders."""
import base64
import glob
import io
import os

from PIL import Image

OUT = "/home/claude/eclesare/public/images"
TS = "/home/claude/eclesare/src/lib/images.ts"
os.makedirs(os.path.dirname(TS), exist_ok=True)

entries = []
for path in sorted(glob.glob(f"{OUT}/*.webp")):
    name = os.path.basename(path)[:-5]
    im = Image.open(path)
    tiny = im.copy().convert("RGB")
    tiny.thumbnail((16, 16), Image.LANCZOS)
    buf = io.BytesIO()
    tiny.save(buf, "WEBP", quality=35)
    blur = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
    entries.append((name, im.width, im.height, blur))

lines = [
    "// AUTO-GENERATED by scripts/images.py — do not edit by hand.",
    "// Regenerate after adding or replacing a file in /public/images.",
    "",
    "export type ImageAsset = {",
    "  src: string;",
    "  width: number;",
    "  height: number;",
    "  blurDataURL: string;",
    "};",
    "",
    "export const images = {",
]
for name, w, h, blur in entries:
    key = name.replace("-", "_")
    lines.append(f'  "{key}": {{')
    lines.append(f'    src: "/images/{name}.webp",')
    lines.append(f"    width: {w},")
    lines.append(f"    height: {h},")
    lines.append(f'    blurDataURL: "{blur}",')
    lines.append("  },")
lines += [
    "} as const satisfies Record<string, ImageAsset>;",
    "",
    "export type ImageKey = keyof typeof images;",
    "",
]

with open(TS, "w") as f:
    f.write("\n".join(lines))

print(f"wrote {TS} with {len(entries)} assets")
for name, w, h, _ in entries:
    print(f"  {name:34s} {w}x{h}")
